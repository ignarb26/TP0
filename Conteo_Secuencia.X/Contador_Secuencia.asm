#include "p16f887.inc"

; CONFIG1
; __config 0x3FFF
 __CONFIG _CONFIG1, _FOSC_EXTRC_CLKOUT & _WDTE_ON & _PWRTE_OFF & _MCLRE_ON & _CP_OFF & _CPD_OFF & _BOREN_ON & _IESO_ON & _FCMEN_ON & _LVP_ON
; CONFIG2
; __config 0x3FFF
 __CONFIG _CONFIG2, _BOR4V_BOR40V & _WRT_OFF

;VARIABLES
 
    CONTADOR EQU 0X20
    SECUENCIA EQU 0X20
    TIME1 EQU 0X20
    TIME2 EQU 0X20
 
    ORG 0X00
    GOTO INICIO

;INICIALIZACION
    
    ORG 0X05
    INICIO
	
	BCF STATUS, RP0
	BSF STATUS, RP1 ;RP0=0, RP1=1, BANCO 2
	
	CLRF TRISD ;PORTD COMO SALIDA
	BSF TRISC, 0 ;RC0 COMO ENTRADA
	
	BCF STATUS, RP1
	CLRF PORTD ;PORTD EN 0
	
	CLRF CONTADOR ;INICIALIZA EL CONTADOR
	
	MOVLW b'00000001'
	MOVWF SECUENCIA ;INICIALIZA SECUENCIA
	
;PROGRAMA PRINCIPAL	
	
	PRINCIPAL
	
	CALL SELECCIONAR_MODO
	
	GOTO PRINCIPAL
	
;SUBRUTINAS
	
	SELECCIONAR_MODO
	
	BTFSS PORTC, 0 ;REVISAMOS ESTADO DEL BOTON
	GOTO MODO_CONTADOR
	
	GOTO MODO_BARRIDO
	
;MODO CONTADOR
	
	MODO_CONTADOR
	
	MOVF CONTADOR, W
	MOVWF PORTD
	
	CALL DELAY
	
	INCF CONTADOR, F
	RETURN
	
;MODO BARRIDO
	
	MODO_BARRIDO
	
	MOVF SECUENCIA, W
	MOVWF PORTD
	
	CALL DELAY
	
	MOVF SECUENCIA, W ;TERMINAMOS LA SECUENCIA?
	XORLW b'10000000'
	
	BTFSC STATUS, Z
	GOTO REINICIAR_BARRIDO
	
	BCF STATUS, C ;SIGUIENTE LED
	RLF SECUENCIA, F
	
	RETURN
	
;REINICIO DEL BARRIDO
	
	REINICIAR_BARRIDO
	
	MOVLW b'00000001' ;ESTADO INICIAL DE LA SECUENCIA
	MOVWF SECUENCIA
	
	RETURN
	
;DELAYS
	
	DELAY
	
	MOVLW d'97'
	MOVWF TIME1
	
	D1
	
	MOVLW d'250'
	MOVWF TIME2
	
	D2
	
	DECFSZ TIME2, F
	GOTO D2
	
	DECFSZ TIME1, F
	GOTO D1
	
	RETURN
	
	
	END